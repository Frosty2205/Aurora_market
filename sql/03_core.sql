-- Esquema de core
-- Convenciones:
--   * Clave sustituta propia (xxx_id) + id del ERP con UNIQUE (trazabilidad y
--     base de los upserts)
--   * id_ejecucion es la última ejecución que creó o modificó el registro
--   * Registro "desconocido" con id -1 en cliente y producto, para no perder
--     ventas cuyo cliente/producto aún no ha llegado (se reasignan después)
--   * PostgreSQL NO indexa las claves foráneas automáticamente: se crean a mano
--     las que se usan en joins o filtros frecuentes

-- Catálogos

CREATE TABLE IF NOT EXISTS core.pais (
    codigo_pais     CHAR(2)     PRIMARY KEY CHECK (codigo_pais ~ '^[A-Z]{2}$'),  -- Esto es según la ISO 3166-1 alfa-2
    nombre          VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS core.canal (
    canal_id        SMALLINT    PRIMARY KEY,
    codigo          VARCHAR(20) NOT NULL UNIQUE,
    nombre          VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS core.estado_pedido (
    estado_id         SMALLINT    PRIMARY KEY,
    codigo            VARCHAR(20) NOT NULL UNIQUE,
    nombre            VARCHAR(40) NOT NULL,
    es_final          BOOLEAN     NOT NULL,   -- no admite más cambios
    cuenta_como_venta BOOLEAN     NOT NULL    -- alimenta consume.fact_ventas.es_venta_valida
);

CREATE TABLE IF NOT EXISTS core.categoria (
    categoria_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS core.subcategoria (
    subcategoria_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id    INT         NOT NULL REFERENCES core.categoria (categoria_id),
    nombre          VARCHAR(60) NOT NULL,
    CONSTRAINT uq_subcategoria UNIQUE (categoria_id, nombre)   -- también sirve de índice de la FK
);

-- Productos

CREATE TABLE IF NOT EXISTS core.producto (
    producto_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto_erp     VARCHAR(20)   NOT NULL UNIQUE,
    nombre              VARCHAR(150)  NOT NULL,
    subcategoria_id     INT           NOT NULL REFERENCES core.subcategoria (subcategoria_id),
    marca               VARCHAR(60),
    precio_lista        NUMERIC(10,2) CHECK (precio_lista >= 0),   -- No pongo NULL para que pueda haber productos sin precio
    coste               NUMERIC(10,2) CHECK (coste >= 0),
    activo              BOOLEAN       NOT NULL DEFAULT true,
    fecha_creacion      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMPTZ   NOT NULL DEFAULT now(),
    id_ejecucion        BIGINT        REFERENCES control.ejecucion (id_ejecucion)
);

CREATE INDEX IF NOT EXISTS ix_producto_subcategoria ON core.producto (subcategoria_id);

-- Cliente: identidad (cliente) + ids del ERP (cliente_id_erp) + historial (cliente_version)

-- Identidad estable del cliente deduplicado ("registro maestro")
CREATE TABLE IF NOT EXISTS core.cliente (
    cliente_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_alta          DATE,
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    id_ejecucion        BIGINT      REFERENCES control.ejecucion (id_ejecucion)
);

-- Correspondencia id del ERP -> cliente maestro
-- Si dos ids del ERP son la misma persona, ambos apuntan al mismo cliente_id
CREATE TABLE IF NOT EXISTS core.cliente_id_erp (
    id_cliente_erp      VARCHAR(20) PRIMARY KEY,
    cliente_id          BIGINT      NOT NULL REFERENCES core.cliente (cliente_id),
    motivo_asignacion   VARCHAR(20) NOT NULL
                        CHECK (motivo_asignacion IN ('alta', 'fusion_duplicado', 'manual')),
    fecha_asignacion    TIMESTAMPTZ NOT NULL DEFAULT now(),
    id_ejecucion        BIGINT      REFERENCES control.ejecucion (id_ejecucion)
);

CREATE INDEX IF NOT EXISTS ix_cliente_id_erp_cliente ON core.cliente_id_erp (cliente_id);

-- Atributos que cambian, con historial SCD tipo 2
CREATE TABLE IF NOT EXISTS core.cliente_version (
    cliente_version_id       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    cliente_id               BIGINT       NOT NULL REFERENCES core.cliente (cliente_id),
    nombre                   VARCHAR(80)  NOT NULL,
    apellidos                VARCHAR(120),
    email                    VARCHAR(254)            -- normalizado a minúsculas, NULL si vacío o inválido
                             CHECK (email = lower(email) AND email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[a-z]{2,}$'),
    telefono                 VARCHAR(20),            -- normalizado: solo dígitos y prefijo '+'
    codigo_pais              CHAR(2)      REFERENCES core.pais (codigo_pais),
    ciudad                   VARCHAR(80),
    consentimiento_marketing BOOLEAN,                -- NULL = desconocido lo vamos a tratar como NO
    valido_desde             TIMESTAMPTZ  NOT NULL,
    valido_hasta             TIMESTAMPTZ,
    es_actual                BOOLEAN      NOT NULL,
    hash_atributos           CHAR(32)     NOT NULL,  -- MD5 de los atributos: si no cambia, no hay nueva versión
    id_ejecucion             BIGINT       REFERENCES control.ejecucion (id_ejecucion),
    CONSTRAINT ck_cliente_version_periodo CHECK (valido_hasta IS NULL OR valido_hasta > valido_desde),
    CONSTRAINT ck_cliente_version_actual  CHECK (es_actual = (valido_hasta IS NULL))
);

-- Solo puede haber una versión vigente por cliente
CREATE UNIQUE INDEX IF NOT EXISTS ux_cliente_version_actual
    ON core.cliente_version (cliente_id) WHERE es_actual;
-- Consultas "cómo era el cliente en la fecha X"
CREATE INDEX IF NOT EXISTS ix_cliente_version_periodo
    ON core.cliente_version (cliente_id, valido_desde);
-- Detección de duplicados por email
CREATE INDEX IF NOT EXISTS ix_cliente_version_email
    ON core.cliente_version (email) WHERE es_actual AND email IS NOT NULL;

COMMENT ON COLUMN core.cliente_version.consentimiento_marketing IS
    'true/false normalizado desde S, SI, 1 / N, NO, 0. NULL = desconocido';

-- Pedido, historial de estados y líneas

CREATE TABLE IF NOT EXISTS core.pedido (
    pedido_id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_pedido_erp         VARCHAR(20)   NOT NULL UNIQUE,
    cliente_id            BIGINT        NOT NULL REFERENCES core.cliente (cliente_id),  -- -1 si no existe
    id_cliente_erp_origen VARCHAR(20)   NOT NULL,  -- id tal cual vino, para reasignar si llega el cliente
    fecha_pedido          TIMESTAMP     NOT NULL,  -- hora local del ERP
    canal_id              SMALLINT      NOT NULL REFERENCES core.canal (canal_id),
    estado_id             SMALLINT      NOT NULL REFERENCES core.estado_pedido (estado_id),  -- estado actual
    importe_total_erp     NUMERIC(12,2) NOT NULL CHECK (importe_total_erp >= 0),  -- dato de origen, se contrasta con las líneas
    fecha_creacion        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_actualizacion   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    id_ejecucion          BIGINT        REFERENCES control.ejecucion (id_ejecucion)
);

-- RFM y visión 360: pedidos de un cliente ordenados por fecha
CREATE INDEX IF NOT EXISTS ix_pedido_cliente_fecha ON core.pedido (cliente_id, fecha_pedido);
-- Filtros por periodo
CREATE INDEX IF NOT EXISTS ix_pedido_fecha ON core.pedido (fecha_pedido);
-- Reasignación de pedidos huérfanos cuando llega su cliente (índice parcial, muy pequeño)
CREATE INDEX IF NOT EXISTS ix_pedido_cliente_pendiente
    ON core.pedido (id_cliente_erp_origen) WHERE cliente_id = -1;

-- Historial de estados
-- El ERP no informa de cuándo cambió el estado, así que valido_desde es igual a la fecha de la carga en la que se detectó el cambio
CREATE TABLE IF NOT EXISTS core.pedido_estado_hist (
    historial_id    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT      NOT NULL REFERENCES core.pedido (pedido_id),
    estado_id       SMALLINT    NOT NULL REFERENCES core.estado_pedido (estado_id),
    valido_desde    TIMESTAMPTZ NOT NULL,
    valido_hasta    TIMESTAMPTZ,
    id_ejecucion    BIGINT      REFERENCES control.ejecucion (id_ejecucion),
    CONSTRAINT ck_estado_hist_periodo CHECK (valido_hasta IS NULL OR valido_hasta > valido_desde)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_estado_hist_actual
    ON core.pedido_estado_hist (pedido_id) WHERE valido_hasta IS NULL;
CREATE INDEX IF NOT EXISTS ix_estado_hist_pedido
    ON core.pedido_estado_hist (pedido_id, valido_desde);

CREATE TABLE IF NOT EXISTS core.linea_pedido (
    pedido_id              BIGINT        NOT NULL REFERENCES core.pedido (pedido_id),
    num_linea              SMALLINT      NOT NULL CHECK (num_linea > 0),
    producto_id            INT           NOT NULL REFERENCES core.producto (producto_id),  -- -1 si no existe
    id_producto_erp_origen VARCHAR(20)   NOT NULL,
    cantidad               INT           NOT NULL CHECK (cantidad > 0),
    cantidad_original      INT           NOT NULL,   -- valor del ERP antes de corregir
    cantidad_corregida     BOOLEAN       GENERATED ALWAYS AS (cantidad <> cantidad_original) STORED,
    precio_unitario        NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
    descuento_pct          NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (descuento_pct BETWEEN 0 AND 100),
    importe_linea          NUMERIC(12,2) GENERATED ALWAYS AS
                           (round(cantidad * precio_unitario * (1 - descuento_pct / 100), 2)) STORED,
    fecha_creacion         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    id_ejecucion           BIGINT        REFERENCES control.ejecucion (id_ejecucion),
    PRIMARY KEY (pedido_id, num_linea)            -- también indexa la FK a pedido
);

-- Afinidad de producto y recomendaciones
CREATE INDEX IF NOT EXISTS ix_linea_producto ON core.linea_pedido (producto_id);
-- Reasignación de líneas huérfanas cuando llega su producto
CREATE INDEX IF NOT EXISTS ix_linea_producto_pendiente
    ON core.linea_pedido (id_producto_erp_origen) WHERE producto_id = -1;

COMMENT ON COLUMN core.linea_pedido.cantidad IS
    'Cantidad válida. Si el ERP envió 0 o negativo y el importe del pedido confirma 1, se corrige a 1';
